// Offline proof verification. Check the trusted checksum manifest before claims.
import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {join,resolve} from 'node:path';
import process from 'node:process';
import console from 'node:console';
import {Buffer} from 'node:buffer';
import {TransactionBuilder,Networks,Keypair,xdr} from '@stellar/stellar-sdk';
import {verifyEvidenceIntegrity} from '../../../scripts/verify-evidence-integrity.mjs';
const root=process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new globalThis.URL('.',import.meta.url));
verifyEvidenceIntegrity(root);
const read=(p)=>JSON.parse(readFileSync(join(root,p),'utf8'));
const payer='GCEUQTTH53VMOY6JNXS6ZWGHUCBP64JOWZZIIJSC6LQLBMQGGVIVO6UB';
const key='AAAABgAAAAEblswW+PDBZ8QGOhf7+j8AvTtHrEL+O4eNCZiCZ4RiuwAAABQAAAAB';
const wrapper=read('result.json');const e=wrapper.execution;
assert.equal(e.records.length,1);
const record=e.records[0];
assert.equal(record.outcome,'succeeded');assert.equal(record.entryKey,key);
assert.equal(record.signer.account,payer);assert.equal(record.payer,'bot-testnet');
const pairs=readdirSync(join(root,'rpc')).filter(n=>n.endsWith('-request.json')).map(n=>({request:read('rpc/'+n),response:read('rpc/'+n.replace('-request','-response'))}));
const sends=pairs.filter(p=>p.request.method==='sendTransaction');assert.equal(sends.length,1);
const tx=TransactionBuilder.fromXDR(sends[0].request.params.transaction,Networks.TESTNET);
const hash=Buffer.from(tx.hash()).toString('hex');assert.equal(hash,record.transactionHash);
assert.equal(tx.source,payer);assert.equal(tx.signatures.length,1);
assert(Keypair.fromPublicKey(payer).verify(tx.hash(),tx.signatures[0].signature));
assert.equal(tx.operations.length,1);assert.equal(tx.operations[0].type,'extendFootprintTtl');
assert.equal(tx.operations[0].extendTo,record.extendToLedgers);assert.equal(tx.operations[0].source,undefined);
assert.equal(tx.memo.type,'none');assert(BigInt(tx.fee)<=2000000n);
const footprint=tx.toEnvelope().value.tx.ext.value.resources.footprint;
assert.deepEqual(footprint.readOnly.map(k=>k.toXDR('base64')),[key]);assert.equal(footprint.readWrite.length,0);
const receipt=pairs.filter(p=>p.request.method==='getTransaction').map(p=>p.response.result).find(r=>r.status==='SUCCESS');
assert(receipt);assert.equal(receipt.envelopeXdr,tx.toXDR());
const result=xdr.TransactionResult.fromXDR(receipt.resultXdr,'base64');assert.equal(result.result.type,'txSuccess');
assert(BigInt(result.feeCharged)<=BigInt(tx.fee));
assert.equal(record.after.endsAtLedger,receipt.ledger+record.extendToLedgers);
assert(record.after.observedAtLedger>=receipt.ledger);assert(record.after.endsAtLedger>record.before.endsAtLedger);
const meta=xdr.TransactionMeta.fromXDR(receipt.resultMetaXdr,'base64');assert.equal(meta.type,'v4');
const changes=meta.value.operations[0].changes;assert.deepEqual(changes.map(c=>c.type),['ledgerEntryState','ledgerEntryUpdated']);
const keyHash=createHash('sha256').update(Buffer.from(key,'base64')).digest('hex');
for(const c of changes){assert.equal(c.value.data.type,'ttl');assert.equal(c.value.data.value.keyHash.toXDR('hex'),keyHash);}
assert.equal(changes[0].value.data.value.liveUntilLedgerSeq,record.before.endsAtLedger);
assert.equal(changes[1].value.data.value.liveUntilLedgerSeq,record.after.endsAtLedger);
const attempt=JSON.parse(readFileSync(join(root,'attempt.jsonl'),'utf8').trim());
assert.equal(attempt.intent.transactionHash,hash);
assert.equal(attempt.intent.sourceAccount,tx.source);assert.equal(attempt.intent.sourceSequence,tx.sequence);
assert.equal(attempt.intent.entryKey,key);assert.equal(attempt.intent.targetLedgers,record.extendToLedgers);
assert.deepEqual(attempt.intent.before,record.before);assert.equal(attempt.intent.envelopeFeeStroops,tx.fee);
const before=read('controls-before-response.json').result,after=read('controls-after-response.json').result;
const project=(r)=>r.entries.map(v=>({key:v.key,expiry:v.liveUntilLedgerSeq})).sort((a,b)=>a.key.localeCompare(b.key));
assert.equal(before.entries.length,5);assert.deepEqual(project(before),project(after));
assert(before.latestLedger<=record.before.observedAtLedger && after.latestLedger>=record.after.observedAtLedger);
const trigger=read('trigger.json');assert(trigger.invocationId);assert.equal(trigger.submit,true);
const campaign=read('campaign.json'),config=read('save-config.json');
assert.equal(trigger.sourceCommit,campaign.sourceCommit);assert.equal(trigger.runId,campaign.runId);
assert.equal(createHash('sha256').update(readFileSync(join(root,'save-config.json'))).digest('hex'),campaign.configSha256);
assert.equal(config.contracts.length,1);assert.equal(config.contracts[0].id,record.contracts[0]);
assert.equal(config.defaults.extendToLedgers,record.extendToLedgers);
assert(record.before.endsAtLedger-record.before.observedAtLedger<config.defaults.bumpWhenRemainingLedgersBelow);
assert(record.after.endsAtLedger-record.after.observedAtLedger>config.defaults.bumpWhenRemainingLedgersBelow);
const timer=read('timer-provenance.json');assert.equal(timer.length,2);
for(const row of timer)assert.equal(row.invocationId,trigger.invocationId);
const start=Number(timer[0].timestamp)/1000,end=Number(timer[1].timestamp)/1000;
assert(start<=Date.parse(trigger.startedAt)&&end>=Date.parse(trigger.startedAt));
assert(start>=campaign.notBefore && start<campaign.notAfter);
const armed=readFileSync(join(root,'save-timer-armed.txt'),'utf8');assert(armed.includes('OnActiveUSec=1min'));
const actual=readFileSync(join(root,'save-service-result.txt'),'utf8');assert(actual.includes('Result=success')&&actual.includes('ExecMainStatus=1'));
const intents=readdirSync(join(root,'alerts')).filter(n=>n.endsWith('.intent.json')).map(n=>read('alerts/'+n));
const success=intents.find(i=>i.kind==='bump' && i.notification.body.includes(hash));assert(success);
assert(success.notification.subject.includes('extended'));assert(success.notification.body.includes('CONFIRMED'));
assert(wrapper.alertReceipts.some(r=>r.id===success.id && r.status==='accepted'));
const image=readFileSync(join(root,'explorer.jpg'));assert.equal(image.subarray(0,3).toString('hex'),'ffd8ff');assert(image.length>10000);
console.log(JSON.stringify({hash,sends:1,receiptTtlChangeVerified:true,beforeExpiry:record.before.endsAtLedger,afterExpiry:record.after.endsAtLedger,inclusionLedger:receipt.ledger,expiryIncrease:record.after.endsAtLedger-record.before.endsAtLedger,envelopeFeeStroops:tx.fee,feeChargedStroops:result.feeCharged.toString(),protectedControlsUnchanged:5,successEmailAccepted:true,sourceCommit:trigger.sourceCommit},null,2));
