/**
 * Dashboard revamp reference screens. One shell, so the sidebar cannot drift
 * between screens: each screen is `parts/<name>.main.html` plus an optional
 * `parts/<name>.panel.html` (the side panel, rendered open).
 *
 *   node web-reference/design-language/source/screens/revamp/build.mjs
 *   npx prettier --write web-reference/design-language/source/screens/revamp
 *
 * Writes `<name>.html` next to this file. Renders: see components.md.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

const NAV = [
  {
    items: [
      ['overview', '/dashboard/', 'Overview'],
      ['contracts', '/dashboard/watchlist/', 'Contracts'],
      ['activity', '/dashboard/activity/', 'Activity'],
      ['allowance', '/allowance/', 'Allowance'],
    ],
  },
  {
    section: 'Tools',
    items: [
      ['scanner', '/dashboard/scanner/', 'Scanner'],
      ['blast-radius', '/dashboard/blast-radius/', 'Blast radius'],
      ['decay', '/dashboard/decay/', 'TTL decay'],
    ],
  },
  {
    section: 'Settings',
    items: [
      ['alerts', '/dashboard/alerts/', 'Alerts'],
      ['account', '/login/', 'Account'],
      ['docs', '/docs/', 'Documentation'],
    ],
  },
];

/** Screen name → [title, nav key, account label]. */
const SCREENS = {
  overview: ['Overview', 'overview'],
  'overview-signed-out': ['Overview', 'overview', 'Sign in'],
  'overview-empty': ['Overview', 'overview'],
  contracts: ['Contracts', 'contracts'],
  activity: ['Activity', 'activity'],
  allowance: ['Allowance', 'allowance'],
  scanner: ['Scanner', 'scanner'],
  'blast-radius': ['Blast radius', 'blast-radius'],
  decay: ['TTL decay', 'decay'],
  alerts: ['Alerts', 'alerts'],
  account: ['Account', 'account'],
};

function nav(active, accountLabel = 'Account') {
  return NAV.map(
    (
      g,
    ) => `<div class="nav-group">${g.section ? `\n            <p class="nav-section">${g.section}</p>` : ''}
${g.items
  .map(([key, href, label]) => {
    const text = key === 'account' ? accountLabel : label;
    return key === active
      ? `            <a class="nav-item active" href="${href}" aria-current="page">${text}</a>`
      : `            <a class="nav-item" href="${href}">${text}</a>`;
  })
  .join('\n')}
          </div>`,
  ).join('\n          ');
}

function page(name, [title, active, accountLabel], main, panel) {
  return `<!doctype html>
<!-- Generated by build.mjs from parts/${name}.*.html. Edit the parts, not this file. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title} — Evergreen</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link
      rel="stylesheet"
      href="https://fonts.googleapis.com/css2?family=Inter:wght@400&amp;family=Newsreader:opsz,wght@6..72,400&amp;family=Space+Mono&amp;display=swap"
    />
    <link rel="stylesheet" href="../../templates/base.css" />
    <link rel="stylesheet" href="../alert-preferences.css" />
    <link rel="stylesheet" href="../autopilot-approve.css" />
    <link rel="stylesheet" href="revamp.css" />
  </head>
  <body class="app${panel ? ' panel-open' : ''}">
    <a class="skip" href="#main">Skip to content</a>
    <div class="shell">
      <aside class="sidebar">
        <a class="brand" href="/">
          <span class="mark" aria-hidden="true"></span>
          <span>
            <span class="brand-name">Evergreen</span>
            <span class="brand-sub">Soroban state</span>
          </span>
        </a>
        <nav aria-label="Sections">
          ${nav(active, accountLabel)}
        </nav>
        <div class="sidebar-foot">testnet only</div>
      </aside>
      <div class="content">
        <div class="statusbar">
          <span class="status-item"><span class="dot"></span>Soroban testnet</span>
          <span class="status-item">ledger <span class="mono">5,400,000</span></span>
          <span class="status-item dim">read 12 s ago</span>
        </div>
        <div class="with-panel">
${main.trimEnd().replace(/^/gm, '          ')}
${panel ? panel.trimEnd().replace(/^/gm, '          ') + '\n' : ''}        </div>
      </div>
    </div>
  </body>
</html>
`;
}

const parts = join(here, 'parts');
for (const [name, spec] of Object.entries(SCREENS)) {
  const mainPath = join(parts, `${name}.main.html`);
  if (!existsSync(mainPath)) throw new Error(`missing ${mainPath}`);
  const main = readFileSync(mainPath, 'utf8');
  const panelPath = join(parts, `${name}.panel.html`);
  const panel = existsSync(panelPath) ? readFileSync(panelPath, 'utf8') : undefined;
  writeFileSync(join(here, `${name}.html`), page(name, spec, main, undefined));
  if (panel) writeFileSync(join(here, `${name}-panel.html`), page(name, spec, main, panel));
}
const unknown = readdirSync(parts).filter(
  (f) => !Object.keys(SCREENS).some((n) => f.startsWith(`${n}.`)),
);
if (unknown.length) throw new Error(`parts with no screen: ${unknown.join(', ')}`);
console.log(`built ${Object.keys(SCREENS).length} screens`);
